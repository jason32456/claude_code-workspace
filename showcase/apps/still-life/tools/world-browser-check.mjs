import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
const out = process.argv[2] || '/tmp/claude-0/shots';
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const page = await browser.newPage();
await page.setViewportSize({ width: 1300, height: 800 });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', (e) => errors.push(String(e)));
await page.goto('http://localhost:8142/dev/world-truth.html', { waitUntil: 'load' });
const info = () => page.evaluate(() => window.__world.info());
await page.waitForTimeout(700);
await page.keyboard.down('ArrowRight');
await page.waitForTimeout(500);
console.log('after pressing right on title:', (await info()).state);
await page.keyboard.up('ArrowRight');
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/intro-title.png` });
await page.waitForTimeout(3300);
console.log('state after intro:', (await info()).state);
const before = await page.evaluate(() => window.__world.debug.rt.player.ox);
await page.keyboard.down('KeyD');
await page.waitForTimeout(600);
await page.keyboard.up('KeyD');
const after = await page.evaluate(() => window.__world.debug.rt.player.ox);
console.log('player moved with WASD:', after - before, 'cells');
await page.waitForTimeout(1200);
await page.screenshot({ path: `${out}/L1-still.png` });
const masks = await page.evaluate(async () => {
  const { textMask } = await import('../js/shape.js');
  return ['MOVE', 'YOU ARE STILL HERE', 'EVERY FRAME WAS NOISE', 'MOVE TO BEGIN AGAIN', 'THEY STOP TOO', 'MOVE TO BEGIN'].map((s) => [s, textMask(s, { height: s.length > 16 ? 16 : 18 }).w]);
});
console.log('text widths', JSON.stringify(masks));
await page.keyboard.press(']');
await page.keyboard.press('Space');
// touch / pointer stick
await page.mouse.move(600, 400);
await page.mouse.down();
await page.mouse.move(680, 400, { steps: 4 });
const read = await page.evaluate(() => window.__input.read());
await page.mouse.up();
console.log('pointer stick read:', JSON.stringify(read));
console.log('errors', errors);
await browser.close();
